// Export a session as JSON (everything), CSV (the apps table) or Markdown (a readable report).
import { segmentStats } from './analysis.mjs';
import { STORE_LABEL } from './pipeline.mjs';
import { human } from './lib/util.mjs';

export const PARTS = ['apps', 'platforms', 'reviews', 'segments', 'openings', 'questions'];

const csvCell = (v) => {
  const s = v == null ? '' : String(v);
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
};

function platformRows(s) {
  return Object.entries(s.progress.perStore).map(([k, v]) => ({
    platform: STORE_LABEL[k], apps: v.apps, reviews: v.reviews, revenueKnown: s.apps.filter((a) => a.store === k && a.revenue != null).length, status: v.status,
  }));
}

export function exportSession(s, format = 'json', parts = PARTS) {
  const want = new Set(parts && parts.length ? parts : PARTS);
  const g = s.grouping || { segments: [], keywords: [], openings: [] };
  const segName = (id) => g.segments.find((x) => x.id === id)?.name || '';
  const kwName = (id) => g.keywords.find((x) => x.id === id)?.name || '';
  const base = s.id;

  if (format === 'csv') {
    const cols = ['name', 'platform', 'developer', 'segment', 'keyword', 'users', 'users_label', 'users_rank', 'rating', 'price', 'est_revenue_month', 'revenue_label', 'revenue_method', 'top_grossing_rank', 'top_complaint', 'url'];
    const rows = s.apps.map((a) => [a.name, STORE_LABEL[a.store], a.developer, segName(a.seg), kwName(a.kw), a.users, a.usersLabel, ['dim', 'medium', 'bright'][a.tier], a.rating, a.priceLabel, a.revenue, a.revenueLabel, a.revenueMethod, a.topGrossingRank, a.complaint || a.lowReviews?.[0]?.title, a.url]);
    return { filename: `${base}-apps.csv`, mimeType: 'text/csv', text: [cols, ...rows].map((r) => r.map(csvCell).join(',')).join('\n') + '\n' };
  }

  if (format === 'md') {
    const L = [`# ${s.name}`, '', `Market ${s.market.toUpperCase()} · ${s.apps.length} apps · data as of ${s.updated.slice(0, 10)} · generated by App Scout`, ''];
    if (want.has('platforms')) {
      L.push('## Platforms', '', '| Platform | Apps | Reviews read | Revenue known |', '|---|---|---|---|');
      for (const p of platformRows(s)) L.push(`| ${p.platform} | ${p.apps} | ${p.reviews} | ${p.revenueKnown} |`);
      L.push('');
    }
    if (want.has('segments') && g.segments.length) {
      L.push('## Segments', '', '| Segment | Apps | Crowded | Revenue known | Est. revenue (known) | Money gaps |', '|---|---|---|---|---|---|');
      for (const x of g.segments) {
        const st = segmentStats(x, s.apps, s.apps.length);
        L.push(`| ${x.name} | ${st.apps} | ${st.crowded ? 'Yes' : 'No'} | ${st.revenueKnown} of ${st.apps} | ${st.revenueSum ? '$' + human(st.revenueSum) + '/mo est.' : 'Unknown'} | ${st.moneyGaps} |`);
      }
      L.push('');
      for (const x of g.segments) if (x.insight) L.push(`- **${x.name}:** ${x.insight}`);
      L.push('');
    }
    if (want.has('openings') && g.openings.length) {
      L.push('## Openings', '');
      for (const o of g.openings) L.push(`- **${o.name}:** ${o.insight}${o.evidence?.length ? ` (evidence: ${o.evidence.join(', ')})` : ''}`);
      L.push('');
    }
    if (want.has('apps')) {
      L.push('## Apps by estimated revenue', '', '| App | Platform | Segment | Users | Est. revenue | Price |', '|---|---|---|---|---|---|');
      for (const a of [...s.apps].sort((x, y) => (y.revenue ?? -1) - (x.revenue ?? -1)).slice(0, 50)) {
        L.push(`| [${a.name}](${a.url}) | ${STORE_LABEL[a.store]} | ${segName(a.seg)} | ${a.usersLabel || '—'} | ${a.revenueLabel} | ${a.priceLabel || '—'} |`);
      }
      L.push('', 'Revenue estimates: user base × 30% active × 1–4% paid × lowest monthly price. Confidence L (App Store, from ratings) or M (published installs). Never a measured number.', '');
    }
    if (want.has('reviews')) {
      const withReviews = s.apps.filter((a) => a.lowReviews?.length);
      if (withReviews.length) {
        L.push('## Review complaints (App Store, 1–2 stars)', '');
        for (const a of withReviews) L.push(`- **${a.name}:** ${a.lowReviews.slice(0, 2).map((r) => `"${r.title}"`).join(', ')}`);
        L.push('');
      }
    }
    if (want.has('questions') && s.questions.length) {
      L.push('## Questions and answers', '');
      for (const q of s.questions) L.push(`**Q:** ${q.text}`, '', q.answer ? `**A:** ${q.answer}` : '_Not answered yet._', '');
    }
    return { filename: `${base}-report.md`, mimeType: 'text/markdown', text: L.join('\n') };
  }

  const out = { session: { id: s.id, name: s.name, market: s.market, topic: s.topic, plan: s.plan, created: s.created, updated: s.updated, target: s.target } };
  if (want.has('apps')) out.apps = s.apps.map(({ x, y, ...a }) => a);
  if (want.has('platforms')) out.platforms = platformRows(s);
  if (want.has('reviews')) out.reviews = s.apps.filter((a) => a.lowReviews?.length).map((a) => ({ app: a.name, low: a.lowReviews }));
  if (want.has('segments')) out.segments = g.segments.map((x) => ({ ...x, keywords: g.keywords.filter((k) => k.seg === x.id), stats: segmentStats(x, s.apps, s.apps.length) }));
  if (want.has('openings')) out.openings = g.openings;
  if (want.has('questions')) out.questions = s.questions;
  return { filename: `${base}.json`, mimeType: 'application/json', text: JSON.stringify(out, null, 2) };
}
